    RETLW   00000110B ; i
    RETLW   01011110B ; d
    
MAIN: 
    CLRF    CON,a 
MAIN_1:
    MOVF    CON,W,a
    CALL    TABLA
    MOVWF   PORTB,a
    CALL    RET_1SEG
    MOVF    CON,W,a
    SUBLW   000111000B	;56
    BTFSS   STATUS,2,a
    GOTO    INCRE
    GOTO    MAIN
    
INCRE:
    INCF    CON,F,a
    INCF    CON,F,a
    GOTO    MAIN_1

RET_1SEG:
    MOVLW   0X85
    MOVWF   TMR0H,a
    MOVLW   0XEE
    MOVWF   TMR0L,a
    MOVLW   10010101B
    MOVWF   T0CON, a
    
CICLO: 
    BTFSS   INTCON,2,a
    GOTO    CICLO
    BCF	    INTCON,2,a
