CONFIGURACION_SFR:; MAIN:
PSECT CODE,RELOC=2
ORG 0X20 ;PARA SALTAR COMPLETAMENTE EL VECTOR INTERRUPCION
CON EQU 0X0D

INICIO:
    CLRF    ADCON0,a ; limpiar el adcon 0, para que quede el registro como digital
    MOVLW   0X0F ; mueve el 15 a W
    MOVWF   ADCON1,a ;de w al ADCON1, MUEVO EL 15
    MOVLW   00000111B ; MUEVO EL VALOR DE 7 A W ; CONFIGURA LOS COMPARADORES PARA ENTRADA DIGITAL
    MOVWF   CMCON,a
    MOVLW   11111111B
    MOVWF   OSCCON,a
    MOVLW   00000000B
    MOVWF   TRISA,a
    CLRF    PORTA,a ; 0 EN EL ACCES BANK
    MOVLW   00000000B
    MOVWF   TRISB,a ; 0 EN EL ACCES BANK
    CLRF    PORTB,a
    GOTO    MAIN

	; Empieza aqui

TABLA:
    ADDWF   PCL, f, a
    
    RETLW   01100111B ; q
    RETLW   00111110B ; U aprox.
    RETLW   00000110B ; i
    RETLW   01010000B ; r aprox.
    RETLW   00000110B ; i
    RETLW   01010100B ; n aprox.
    RETLW   00111111B ; O

